#!/usr/bin/env python3
"""Generates params_gen.h from params.def (the one table of all tunable parameters).

  python3 tools/gen_params.py            write params_gen.h
  python3 tools/gen_params.py --check    exit 1 if params_gen.h is not what params.def produces (regress.sh runs this)
  python3 tools/gen_params.py --spsa tools/spsa/spsa_params_round5.txt   check that every name of the file is a parameter
  python3 tools/gen_params.py --set "$(cat spsa1/result.txt)"            make the values of an SPSA result ("-DNAME=value ...") the new
                                                                         defaults in params.def, then regenerate (after the SPRT passed)

Why a generated file: a C macro cannot emit #ifndef / #undef / #define, and -DNAME=value overrides (make EXTRA=..., SPSA results) need the
#ifndef. Everything else (tune variables, UCI options, table) is made by X-macros directly from params.def, see params.h / params.c.
"""
import os, re, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
if os.path.isdir(os.path.join(root, 'src')):   # the released layout keeps the engine sources in src/
    root = os.path.join(root, 'src')
PARAMS = []
for line in open(os.path.join(root, 'params.def'), 'rb').read().decode().splitlines():
    m = re.match(r'X\((\w+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\)', line)
    if m:
        PARAMS.append((m.group(1), int(m.group(2)), int(m.group(3)), int(m.group(4))))
names = [p[0] for p in PARAMS]
assert len(set(names)) == len(names), 'duplicate parameter'
for n, d, lo, hi in PARAMS:
    assert lo <= d <= hi, '%s: default %d outside %d..%d' % (n, d, lo, hi)

def generate():
    o = ['// GENERATED by tools/gen_params.py from params.def. do not edit.',
         '#ifndef PARAMS_GEN_H', '#define PARAMS_GEN_H', '',
         '// defaults (a -DNAME=value flag wins); NAME_GEN is only used by params.h to notice a stale file']
    for n, d, lo, hi in PARAMS:
        o += ['#ifndef %s' % n, '#define %s %d' % (n, d), '#endif', '#define %s_GEN %d' % (n, d)]
    o += ['', '#ifdef TUNE_SEARCH', '// tune build: every parameter is a variable tune_NAME (params.c) that starts at the value above',
          '// (the default or the -D value); tune_init_NAME keeps that start value for the UCI option list']
    for n, d, lo, hi in PARAMS:
        o += ['enum { tune_init_%s = %s };' % (n, n), '#undef %s' % n, '#define %s tune_%s' % (n, n)]
    o += ['#endif', '', '#endif', '']
    return '\n'.join(o)

path = os.path.join(root, 'params_gen.h')
if '--set' in sys.argv:
    flags = sys.argv[sys.argv.index('--set') + 1]
    new = {}
    for m in re.finditer(r'-D(\w+)=(-?\d+)', flags):
        assert m.group(1) in names, 'unknown parameter ' + m.group(1)
        new[m.group(1)] = int(m.group(2))
    assert new, 'no -DNAME=value found'
    defpath = os.path.join(root, 'params.def')
    text = open(defpath, 'rb').read().decode()
    for n, v in new.items():
        lo, hi = [(p[2], p[3]) for p in PARAMS if p[0] == n][0]
        assert lo <= v <= hi, '%s=%d outside %d..%d' % (n, v, lo, hi)
        text, c = re.subn(r'^X\(%s, -?\d+,' % n, 'X(%s, %d,' % (n, v), text, flags=re.M)
        assert c == 1, n
    open(defpath, 'wb').write(text.encode())
    print('params.def: %d defaults changed' % len(new))
    os.execv(sys.executable, [sys.executable, os.path.abspath(__file__)])   # regenerate params_gen.h
if '--spsa' in sys.argv:
    f = sys.argv[sys.argv.index('--spsa') + 1]
    bad = [l.split()[0] for l in open(f).read().splitlines() if l.strip() and not l.startswith('#') and l.split()[0] not in names]
    print('unknown parameters in %s: %s' % (f, bad or 'none'))
    sys.exit(1 if bad else 0)
new = generate()
# the generated file gets the line endings of params.def (CRLF in the development tree, LF in the release)
nl = '\r\n' if b'\r\n' in open(os.path.join(root, 'params.def'), 'rb').read() else '\n'
if '--check' in sys.argv:
    old = open(path, 'rb').read().decode().replace('\r\n', '\n') if os.path.exists(path) else ''
    if old != new:
        print('params_gen.h is stale: run python3 tools/gen_params.py'); sys.exit(1)
    print('params_gen.h up to date (%d parameters)' % len(PARAMS)); sys.exit(0)
open(path, 'wb').write(new.replace('\n', nl).encode())
print('wrote params_gen.h (%d parameters)' % len(PARAMS))
